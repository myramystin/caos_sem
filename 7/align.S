.section .data

# Адрес:   0x2000  0x2001  0x2002  0x2003  0x2004  0x2005  0x2006  0x2007  0x2008
# Данные:  [0x11] [-------- 0x12345678 --------] [0x22] [-- 0x123456789ABCDEF0 --
#                 ^плохо: int начинается с нечетного адреса    ^плохо: long не выровнен

bad_layout:
    .byte 0x11              # 1 байт на адресе, например, 0x2000
    .long 0x12345678        # 4 байта СРАЗУ после byte - адрес 0x2001 (НЕ кратен 4!)
    .byte 0x22              # 1 байт  
    .quad 0x123456789ABCDEF0 # 8 байт - адрес может быть не кратен 8!

# Адрес:   0x2010  0x2011  0x2012  0x2013  0x2014  0x2015  0x2016  0x2017  0x2018  0x2019  0x201A  0x201B  0x201C  0x201D  0x201E  0x201F  0x2020
# Данные:  [0x11] [padding padding padding] [-------- 0x12345678 --------] [0x22] [padding padding padding padding padding padding padding] [--------
#                                           ^хорошо: int на адресе кратном 4                                                                ^хорошо: long на адресе кратном 8

good_layout:
    .byte 0x11              # 1 байт на адресе 0x2010
    .align 4                # Выравнивание по границе 4 байт

    .long 0x12345678        # 4 байта на адресе 0x2014 (кратен 4 ✓)
    .byte 0x22              # 1 байт на адресе 0x2018
    .align 8                # Выравнивание по границе 8 байт
  
    .quad 0x123456789ABCDEF0 # 8 байт на адресе 0x2020 (кратен 8 ✓)

.section .text
.global main

main:
    # Загрузка из невыровненных данных (может быть медленной)
    leaq bad_layout(%rip), %rbx
    movb (%rbx), %al            # Байт - быстро
    movl 1(%rbx), %ecx          # int с адреса 0x2001 - МЕДЛЕННО!
    
    # Загрузка из выровненных данных (быстро)
    leaq good_layout(%rip), %rdx  
    movb (%rdx), %sil           # Байт - быстро
    movl 4(%rdx), %edi          # int с выровненного адреса - БЫСТРО!
    movq 16(%rdx), %r8          # long с выровненного адреса - БЫСТРО!
    
    # Завершение
    movq $60, %rax
    xorq %rdi, %rdi  
    syscall
